//! O modelo do schema contra um PostgreSQL de verdade: carregar, editar,
//! gerar o DDL, aplicar e recarregar tem que dar o modelo editado.
//!
//! Usa as mesmas variáveis de `tests/catalog.rs`; sem `PGSTUDIO_TEST_HOST`
//! os testes só avisam.

use pgstudio_core::connection::{ConnectionSettings, SslMode};
use pgstudio_core::metadata::MetadataProvider;
use pgstudio_pg_client::{DbRuntime, Session};
use pgstudio_pg_metadata::CatalogExplorer;
use pgstudio_schema_model::edit::Document;
use pgstudio_schema_model::{
    Action, Check, Column, ForeignKey, Identity, Index, Key, Model, Table, diff::diff,
};

fn server() -> Option<(ConnectionSettings, String)> {
    let Ok(host) = std::env::var("PGSTUDIO_TEST_HOST") else {
        eprintln!("PGSTUDIO_TEST_HOST not set; skipping");
        return None;
    };
    let var = |name: &str, default: &str| std::env::var(name).unwrap_or_else(|_| default.into());
    Some((
        ConnectionSettings {
            host,
            port: var("PGSTUDIO_TEST_PORT", "5432").parse().unwrap(),
            database: "postgres".into(),
            user: var("PGSTUDIO_TEST_USER", "postgres"),
            ssl: SslMode::Disable,
        },
        var("PGSTUDIO_TEST_PASSWORD", ""),
    ))
}

const SCHEMA: &str = r#"
CREATE SCHEMA loja;
CREATE TYPE loja.status AS ENUM ('novo', 'pago');
CREATE TABLE loja.cliente (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email text NOT NULL,
    nome text,
    criado_em timestamp with time zone DEFAULT now(),
    CONSTRAINT cliente_email_key UNIQUE (email)
);
CREATE TABLE loja.pedido (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    cliente_id integer NOT NULL,
    qty integer DEFAULT 1,
    preco numeric(10,2),
    total numeric GENERATED ALWAYS AS ((qty)::numeric * preco) STORED,
    CONSTRAINT pedido_pkey PRIMARY KEY (id),
    CONSTRAINT pedido_qty_check CHECK (qty > 0),
    CONSTRAINT pedido_cliente_id_fkey FOREIGN KEY (cliente_id)
        REFERENCES loja.cliente (id) ON DELETE CASCADE
);
CREATE INDEX pedido_cliente_idx ON loja.pedido (cliente_id) WHERE qty > 0;
CREATE INDEX cliente_email_lower ON loja.cliente (lower(email));
CREATE TABLE public."user" ("order" integer, "Nome" text);
"#;

struct TestDb {
    rt: DbRuntime,
    admin: Session,
    name: String,
    explorer: CatalogExplorer,
}

impl TestDb {
    fn create(suffix: &str) -> Option<TestDb> {
        let (settings, password) = server()?;
        let rt = DbRuntime::new().unwrap();
        let admin = rt.block_on(Session::connect(&settings, &password)).unwrap();
        let name = format!("pgstudio_model_{}_{suffix}", std::process::id());
        rt.block_on(admin.simple_query(&format!("DROP DATABASE IF EXISTS {name}")))
            .unwrap();
        rt.block_on(admin.simple_query(&format!("CREATE DATABASE {name}")))
            .unwrap();
        let db = ConnectionSettings {
            database: name.clone(),
            ..settings
        };
        let session = rt.block_on(Session::connect(&db, &password)).unwrap();
        rt.block_on(session.simple_query(SCHEMA)).unwrap();
        let explorer = CatalogExplorer::new(session, password, rt.clone());
        Some(TestDb {
            rt,
            admin,
            name,
            explorer,
        })
    }

    fn load(&self) -> Model {
        self.explorer.load_model(&self.name).unwrap()
    }
}

impl Drop for TestDb {
    fn drop(&mut self) {
        let _ = self.rt.block_on(self.admin.simple_query(&format!(
            "DROP DATABASE IF EXISTS {} WITH (FORCE)",
            self.name
        )));
    }
}

/// O modelo sem ids e em ordem de nome, para comparar o que o banco tem
/// com o que foi editado (objetos novos ganham ids do catálogo ao
/// recarregar).
fn shape(m: &Model) -> Vec<Table> {
    let mut tables: Vec<Table> = m
        .tables
        .iter()
        .cloned()
        .map(|mut t| {
            t.id = 0;
            for c in &mut t.columns {
                c.id = 0;
            }
            t.uniques.sort_by(|a, b| a.name.cmp(&b.name));
            t.checks.sort_by(|a, b| a.name.cmp(&b.name));
            t.foreign_keys.sort_by(|a, b| a.name.cmp(&b.name));
            t.indexes.sort_by(|a, b| a.name.cmp(&b.name));
            t
        })
        .collect();
    tables.sort_by(|a, b| (&a.schema, &a.name).cmp(&(&b.schema, &b.name)));
    tables
}

fn id(m: &Model, schema: &str, name: &str) -> u64 {
    m.find(schema, name).unwrap().id
}

#[test]
fn the_catalog_becomes_a_model() {
    let Some(db) = TestDb::create("load") else {
        return;
    };
    let m = db.load();
    assert_eq!(m.tables.len(), 3);
    let pedido = m.find("loja", "pedido").unwrap();
    let names: Vec<&str> = pedido.columns.iter().map(|c| c.name.as_str()).collect();
    assert_eq!(names, ["id", "cliente_id", "qty", "preco", "total"]);
    let id_col = &pedido.columns[0];
    assert_eq!(
        (id_col.ty.as_str(), id_col.identity, id_col.nullable),
        ("bigint", Some(Identity::ByDefault), false)
    );
    assert_eq!(pedido.columns[2].default.as_deref(), Some("1"));
    assert_eq!(
        pedido.columns[4].generated.as_deref(),
        Some("((qty)::numeric * preco)")
    );
    assert_eq!(pedido.columns[4].default, None);
    assert_eq!(
        pedido.checks,
        [Check {
            name: "pedido_qty_check".into(),
            expr: "qty > 0".into()
        }]
    );
    assert_eq!(
        pedido.foreign_keys,
        [ForeignKey {
            name: "pedido_cliente_id_fkey".into(),
            columns: vec!["cliente_id".into()],
            ref_schema: "loja".into(),
            ref_table: "cliente".into(),
            ref_columns: vec!["id".into()],
            on_update: Action::NoAction,
            on_delete: Action::Cascade,
        }]
    );
    assert_eq!(
        pedido.indexes,
        [Index {
            name: "pedido_cliente_idx".into(),
            unique: false,
            method: "btree".into(),
            columns: vec!["cliente_id".into()],
            predicate: Some("qty > 0".into()),
        }]
    );
    let cliente = m.find("loja", "cliente").unwrap();
    assert_eq!(cliente.indexes[0].columns, ["lower(email)"]);
    assert_eq!(
        cliente.uniques,
        [Key {
            name: "cliente_email_key".into(),
            columns: vec!["email".into()]
        }]
    );
    let types = db.explorer.type_names(&db.name).unwrap();
    assert!(types.iter().any(|t| t == "loja.status"), "{types:?}");
    assert!(types.iter().any(|t| t == "integer"), "{types:?}");
    // Nada a fazer entre o banco e ele mesmo, e recarregar dá o mesmo.
    assert!(diff(&m, &m).is_empty());
    assert_eq!(db.load(), m);
}

#[test]
fn edits_applied_to_the_database_come_back_when_reloaded() {
    let Some(db) = TestDb::create("edit") else {
        return;
    };
    let saved = db.load();
    let mut d = Document::new(saved.clone());
    let cliente = id(&d.model, "loja", "cliente");
    let pedido = id(&d.model, "loja", "pedido");

    // Renomeia a tabela referenciada e a coluna da FK.
    d.rename_table(cliente, "loja", "customer").unwrap();
    let email = d.model.table(cliente).unwrap().column("email").unwrap().id;
    d.rename_column(cliente, email, "e-mail").unwrap();
    let nome = d.model.table(cliente).unwrap().column("nome").unwrap().id;
    d.update_column(cliente, nome, |c| {
        c.ty = "character varying(200)".into();
        c.nullable = false;
        c.default = Some("'sem nome'::character varying".into());
    })
    .unwrap();
    // Pedido: muda a FK, apaga uma coluna, acrescenta outra e um índice.
    d.drop_constraint(pedido, "pedido_cliente_id_fkey").unwrap();
    d.add_foreign_key(
        pedido,
        ForeignKey {
            name: "pedido_customer_fkey".into(),
            columns: vec!["cliente_id".into()],
            ref_schema: "loja".into(),
            ref_table: "customer".into(),
            ref_columns: vec!["id".into()],
            on_update: Action::Cascade,
            on_delete: Action::Restrict,
        },
    )
    .unwrap();
    let preco = d.model.table(pedido).unwrap().column("total").unwrap().id;
    d.drop_column(pedido, preco).unwrap();
    d.add_column(
        pedido,
        Column {
            name: "obs".into(),
            ty: "text".into(),
            nullable: true,
            ..Default::default()
        },
    )
    .unwrap();
    d.add_index(
        pedido,
        Index {
            name: "pedido_obs_idx".into(),
            unique: true,
            method: "btree".into(),
            columns: vec!["obs".into(), "lower(obs)".into()],
            predicate: None,
        },
    )
    .unwrap();
    // Tabela nova com FK e check, num schema existente, com nome reservado.
    let item = d.add_table("loja", "order").unwrap();
    d.add_column(
        item,
        Column {
            name: "pedido_id".into(),
            ty: "bigint".into(),
            nullable: false,
            ..Default::default()
        },
    )
    .unwrap();
    d.add_foreign_key(
        item,
        ForeignKey {
            columns: vec!["pedido_id".into()],
            ref_schema: "loja".into(),
            ref_table: "pedido".into(),
            ref_columns: vec!["id".into()],
            ..Default::default()
        },
    )
    .unwrap();
    d.add_check(
        item,
        Check {
            name: String::new(),
            expr: "pedido_id > 0".into(),
        },
    )
    .unwrap();
    // E apaga a tabela "user".
    d.drop_table(id(&d.model, "public", "user")).unwrap();

    let ddl = diff(&saved, &d.model);
    db.explorer.apply_ddl(&db.name, &ddl).unwrap_or_else(|e| {
        panic!("{e}\n{}", ddl.join("\n"));
    });
    let reloaded = db.load();
    assert_eq!(shape(&reloaded), shape(&d.model), "{}", ddl.join("\n"));
    assert!(
        ddl.iter()
            .any(|s| s == "ALTER TABLE loja.cliente RENAME TO customer;"),
        "{}",
        ddl.join("\n")
    );
    // O banco recarregado e o editado não têm mais nada a aplicar.
    assert!(diff(&reloaded, &reloaded).is_empty());
}

#[test]
fn a_failed_statement_rolls_everything_back() {
    let Some(db) = TestDb::create("rollback") else {
        return;
    };
    let before = db.load();
    let ddl = vec![
        "CREATE TABLE loja.temp (a integer);".to_string(),
        "ALTER TABLE loja.nope ADD COLUMN b integer;".to_string(),
    ];
    let err = db.explorer.apply_ddl(&db.name, &ddl).unwrap_err();
    assert!(err.0.contains("statement 2 of 2"), "{err}");
    assert!(err.0.contains("loja.nope"), "{err}");
    assert_eq!(db.load(), before);
    // A sessão continua usável depois do ROLLBACK.
    db.explorer
        .apply_ddl(&db.name, &["CREATE TABLE loja.ok (a integer);".to_string()])
        .unwrap();
    assert!(db.load().find("loja", "ok").is_some());
}

#[test]
fn keys_indexes_and_checks_from_the_designer_show_up_in_the_explorer_and_scripts() {
    use pgstudio_core::metadata::{Folder, ScriptAction};
    use pgstudio_pg_metadata::{Path, Relation};

    let Some(db) = TestDb::create("keys") else {
        return;
    };
    let saved = db.load();
    let mut d = Document::new(saved.clone());
    let cliente = id(&d.model, "loja", "cliente");
    let pedido = id(&d.model, "loja", "pedido");
    d.update_foreign_key(
        pedido,
        "pedido_cliente_id_fkey",
        ForeignKey {
            name: "pedido_cliente_fk".into(),
            columns: vec!["cliente_id".into()],
            ref_schema: "loja".into(),
            ref_table: "cliente".into(),
            ref_columns: vec!["id".into()],
            on_delete: Action::SetNull,
            ..Default::default()
        },
    )
    .unwrap();
    d.add_unique(
        cliente,
        Key {
            name: String::new(),
            columns: vec!["nome".into(), "email".into()],
        },
    )
    .unwrap();
    d.update_check(
        pedido,
        "pedido_qty_check",
        Check {
            name: "pedido_qty_positiva".into(),
            expr: "qty > 0 AND qty < 1000".into(),
        },
    )
    .unwrap();
    d.update_index(
        pedido,
        "pedido_cliente_idx",
        Index {
            name: "pedido_cliente_qty_idx".into(),
            unique: false,
            method: "btree".into(),
            columns: vec!["cliente_id".into(), "qty".into()],
            predicate: None,
        },
    )
    .unwrap();
    let ddl = diff(&saved, &d.model);
    db.explorer
        .apply_ddl(&db.name, &ddl)
        .unwrap_or_else(|e| panic!("{e}\n{}", ddl.join("\n")));
    assert_eq!(shape(&db.load()), shape(&d.model), "{}", ddl.join("\n"));

    let names = |oid: u64, folder| -> Vec<String> {
        let node = Path::RelationFolder(db.name.clone(), Relation::Table, oid as u32, folder).id();
        db.explorer
            .children(&node)
            .unwrap()
            .into_iter()
            .map(|n| n.name)
            .collect()
    };
    let has = |list: Vec<String>, name: &str| list.iter().any(|n| n.starts_with(name));
    assert!(has(
        names(pedido, Folder::Constraints),
        "pedido_cliente_fk (foreign key)"
    ));
    assert!(has(
        names(pedido, Folder::Constraints),
        "pedido_qty_positiva (check)"
    ));
    assert!(has(
        names(cliente, Folder::Constraints),
        "cliente_nome_email_key"
    ));
    let indexes = names(pedido, Folder::Indexes);
    assert!(
        has(indexes.clone(), "pedido_cliente_qty_idx"),
        "{indexes:?}"
    );

    let script = db
        .explorer
        .script(
            &Path::Table(db.name.clone(), pedido as u32).id(),
            ScriptAction::Create,
        )
        .unwrap();
    for part in [
        "CONSTRAINT pedido_cliente_fk FOREIGN KEY (cliente_id) REFERENCES loja.cliente(id) ON DELETE SET NULL",
        "CONSTRAINT pedido_qty_positiva CHECK (qty > 0 AND qty < 1000)",
        "CREATE INDEX pedido_cliente_qty_idx ON loja.pedido USING btree (cliente_id, qty)",
    ] {
        assert!(script.contains(part), "{part}\n{script}");
    }
}
